-- 012_nome_portugues.sql
-- Nomes em português para a gold mostrar (D-082). É um dado de referência escrito à mão,
-- ligado pelo código, e os nomes originais da API continuam na bronze e na silver.
-- Termos econômicos seguem o uso corrente no Brasil: PIB nominal, PIB real, PPC.

create table silver.nome_portugues (
    categoria text not null,
    codigo    text not null,
    nome      text not null,
    primary key (categoria, codigo),
    constraint nome_portugues_categoria_valida
        check (categoria in ('pais', 'regiao', 'renda', 'indicador', 'agregado')),
    constraint nome_portugues_nome_preenchido check (btrim(nome) <> '')
);

comment on table silver.nome_portugues is
    'Nome em português de cada país, região, faixa de renda, indicador e agregado.';
comment on column silver.nome_portugues.categoria is 'pais, regiao, renda, indicador ou agregado.';
comment on column silver.nome_portugues.codigo is 'O código usado pela API.';
comment on column silver.nome_portugues.nome is 'O nome mostrado nos dashboards.';

-- Sem tradução, a gold mostra o nome original: um código novo da API não some da tela.
create function silver.nome_pt(p_categoria text, p_codigo text, p_original text)
returns text
language sql
stable
as $$
    select coalesce(
        (select nome from silver.nome_portugues
         where categoria = p_categoria and codigo = p_codigo),
        p_original
    )
$$;

comment on function silver.nome_pt(text, text, text) is
    'Nome em português de um código; sem tradução, devolve o nome original.';

